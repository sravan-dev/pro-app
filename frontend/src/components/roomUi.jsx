// Time since this user joined, ticking every second. Kept in its own component
// so the tick re-renders only the clock, not the whole room.
export function CallTimer() {
  const [start] = useState(() => Date.now());
  const [now, setNow] = useState(start);
  useEffect(() => {
    const t = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(t);
  }, []);
  const secs = Math.floor((now - start) / 1000);
  const pad = (n) => String(n).padStart(2, '0');
  return <>{pad(Math.floor(secs / 3600))}:{pad(Math.floor(secs / 60) % 60)}:{pad(secs % 60)}</>;
}

// Kicker (brand dots + label), title and subtitle at the top of the stage card.
export function RoomTitle({ kicker, title, subtitle }) {
  return (
    <div style={{ minWidth: 0 }}>
      <div className="vr-kicker"><span className="vr-dots" aria-hidden="true"><i /><i /><i /><i /></span>{kicker}</div>
      <h3 className="vr-title">{title}</h3>
      {subtitle && <p className="vr-subtitle">{subtitle}</p>}
    </div>
  );
}

// Navy initial disc whose ring cycles the brand accents by list position.
export function Avatar({ name, index = 0, large = false }) {
  return (
    <span className={`vr-avatar${large ? ' vr-avatar-lg' : ''} vr-ring-${index % 4}`}>
      {name?.trim()?.[0]?.toUpperCase() || '?'}
    </span>
  );
}

// Today's (or the session's) date for the stage subtitle.
export const formatRoomDate = (when) => {
  const d = when ? new Date(when) : null;
  return (d && !isNaN(d) ? d : new Date())
    .toLocaleDateString(undefined, { weekday: 'short', day: 'numeric', month: 'long', year: 'numeric' });
};
